<?php
/**
 * Single Master File Queue Sync Module (/etc/asterisk/pbx/queues_pbx.conf)
 * Consolidates all active call center queues into a single master configuration file reading from `queues_details` key-value table.
 */

require_once __DIR__ . '/../queue_helper.php';
require_once __DIR__ . '/../services/QueueCallbackService.php';

function syncQueue($queue_id) {
    return syncAllQueues();
}

function syncAllQueues() {
    return withSyncLock('queues', '__syncAllQueuesBody');
}

function __syncAllQueuesBody() {
    $db = getDB();
    $queues = $db->query("SELECT * FROM pbx_queues WHERE is_active = 1 ORDER BY queue_name ASC")->fetchAll(PDO::FETCH_ASSOC);

    $conf = "; ==========================================================\n";
    $conf .= "; Master Call Center Queues Configuration (Auto-generated by AI PBX via queues_details DB)\n";
    $conf .= "; ==========================================================\n\n";

    $conf .= "[general]\n";
    $conf .= "persistentmembers = yes\n";
    $conf .= "autofill = yes\n";
    $conf .= "monitor-type = MixMonitor\n";
    $conf .= "queue_log = yes\n\n";
    $callbacks = "; Queue callback requests (generated)\n";

    // Ring registered devices only. A forward or extension voicemail must not answer on the agent's behalf.
    $callbacks .= '[' . QueueCallbackService::AUTO_AGENT_CONTEXT . "]\n" . <<<'DIALPLAN'
exten => _X!,1,Set(CHANNEL(hangup_handler_push)=aipbx-auto-callback-result,s,1(agent_unanswered))
 same => n,Set(CB_AGENT=${FILTER(0-9,${CUT(EXTEN,-,2)})})
 same => n,GotoIf($["${CB_AGENT}" = ""]?done)
 same => n,GotoIf($["${EXTENSION_STATE(${CB_AGENT}@from-internal-pbx-ortak)}" != "NOT_INUSE"]?done)
 same => n,Set(C_SIP=${PJSIP_DIAL_CONTACTS(${CB_AGENT}-sip)})
 same => n,Set(C_WEB=${PJSIP_DIAL_CONTACTS(${CB_AGENT}-webrtc)})
 same => n,Set(C_MOB=${PJSIP_DIAL_CONTACTS(${CB_AGENT}-mob-webrtc)})
 same => n,Set(DIAL_CONTACTS=${C_SIP}${IF($["${C_SIP}" != "" & "${C_WEB}" != ""]?&)}${C_WEB})
 same => n,Set(DIAL_CONTACTS=${DIAL_CONTACTS}${IF($["${DIAL_CONTACTS}" != "" & "${C_MOB}" != ""]?&)}${C_MOB})
 same => n,GotoIf($["${DIAL_CONTACTS}" = ""]?done)
 same => n,Dial(${DIAL_CONTACTS},20,i)
 same => n(done),Hangup()

[aipbx-auto-callback-out]
exten => _[+0-9]X!,1,Set(CHANNEL(hangup_handler_push)=aipbx-auto-callback-result,s,1(customer_unanswered))
 same => n,Gosub(aipbx-auto-callback-result,s,1(calling_customer))
 same => n,Goto(${AIPBX_AUTO_CB_CONTEXT},${EXTEN},1)

[aipbx-auto-callback-result]
exten => s,1,ExecIf($["${FILTER(0-9,${AIPBX_AUTO_CB_ID})}" != ""]?System(/usr/local/bin/queue_callback.php result '${FILTER(0-9,${AIPBX_AUTO_CB_ID})}' '${FILTER(0-9,${AIPBX_AUTO_CB_ATTEMPT})}' '${FILTER(a-z_,${ARG1})}'))
 same => n,Return()
DIALPLAN;
    $callbacks .= "\n\n";

    foreach ($queues as $q) {
        $q_name = $q['queue_name'];
        $title = toCleanAscii($q['title']);
        $musicclass = toCleanAscii(!empty($q['musicclass']) ? $q['musicclass'] : 'default');

        // Fetch details map from `queues_details` table
        $q_map = QueueHelper::getDetailsMap($q_name);
        if (empty($q_map)) {
            QueueHelper::syncQueueToDetails($q);
            $q_map = QueueHelper::getDetailsMap($q_name);
        }

        $conf .= "; Call Center Queue ID {$q['id']}: {$title} ({$q_name})\n";
        $conf .= "[{$q_name}]\n";
        $conf .= "musicclass={$musicclass}\n";
        // Always derive this protected exit context from the current queue row, not a stale map.
        if (!empty($q['callback_enabled']) || str_starts_with((string) ($q_map['context'] ?? ''), 'aipbx-callback-')) {
            unset($q_map['context']);
        }
        if (!empty($q['callback_enabled'])) {
            $id = (int) $q['id'];
            $confirmation = FileHelper::sanitizeAudioPath((string) ($q['callback_announce'] ?? '')) ?: 'queue-thankyou';
            $conf .= "context=aipbx-callback-{$id}\n";
            $callbacks .= "[aipbx-callback-{$id}]\n"
                . "exten => 1,1,Answer()\n"
                . " same => n,Set(CALLBACK_RESULT=\${SHELL(/usr/local/bin/queue_callback.php {$id} '\${FILTER(0-9+,\${CALLERID(num)})}')})\n"
                . " same => n,GotoIf(\$[\"\${CALLBACK_RESULT}\" != \"OK\"]?failed)\n"
                . " same => n,Playback({$confirmation})\n"
                . " same => n,Hangup()\n"
                . " same => n(failed),Playback(sorry)\n"
                . " same => n,Hangup()\n\n";
        }

        // Output all key-value directives stored in `queues_details`
        // Note: monitor-format is omitted to avoid duplicate MixMonitor collisions
        // with the dialplan MixMonitor managed in DialplanDestinationBuilder.
        foreach ($q_map as $k => $v) {
            if ($v === '' || $v === null || $k === 'monitor-format') continue;
            $conf .= toCleanAscii($k) . "=" . confValue(toCleanAscii($v)) . "\n";
        }

        // Static agents: a member loaded from the config is not "dynamic" for
        // Asterisk, cannot be removed with "queue remove member", only paused.
        // The interface/state_interface are kept exactly the same as the dynamic
        // entry (QueueHelper::setMembership) — otherwise the same agent would
        // show up as two separate members.
        // Skill levels (member_levels_json): a lower level is rung first.
        $levels = json_decode((string) ($q['member_levels_json'] ?? ''), true) ?: [];
        foreach (QueueHelper::staticMembersOf($q) as $s_ext) {
            $s_ext = preg_replace('/[^0-9]/', '', $s_ext);
            if ($s_ext === '') continue;
            $level = (int) ($levels[$s_ext] ?? 0);
            $conf .= "member => Local/{$s_ext}@from-internal-pbx/n,{$level},Agent {$s_ext},hint:{$s_ext}@from-internal-pbx\n";
        }
        $conf .= "\n";
    }

    // Delete old individual queue files if any exist
    $old_files = glob(ASTERISK_PBX_DIR . '/queue_*.conf');
    if (is_array($old_files)) {
        foreach ($old_files as $f) {
            FileHelper::deleteFile($f);
        }
    }

    $result = writeConfsWithRollback([
        'extensions_queue_callbacks.conf' => $callbacks,
        'queues_pbx.conf' => $conf,
    ], function () {
        refreshAdvancedFileOverlay('queues');
        AsteriskHelper::assertReloadsOk([
            AsteriskHelper::execCLI('dialplan reload'),
            AsteriskHelper::reloadQueue('all'),
        ], t('sync.ctx_queues'));
    }, t('sync.ctx_queues'));

    foreach ($queues as $q) {
        purgeStaticFromPersistentMembers($q['queue_name'], QueueHelper::staticMembersOf($q));
        // Logged-in dynamic members take a changed level at once (a static one has it from the file).
        $levels = json_decode((string) ($q['member_levels_json'] ?? ''), true) ?: [];
        $static = QueueHelper::staticMembersOf($q);
        foreach (json_decode((string) ($q['members_json'] ?? '[]'), true) ?: [] as $m) {
            $m = preg_replace('/[^0-9]/', '', (string) $m);
            if ($m !== '' && !in_array($m, $static, true)) {
                AsteriskHelper::execCLI(sprintf('queue set penalty %d on Local/%s@from-internal-pbx/n in %s', (int) ($levels[$m] ?? 0), $m, $q['queue_name']));
            }
        }
    }

    return $result;
}

/**
 * The old entry of an agent switched from dynamic to static stays in the
 * Queue/PersistentMembers/<queue> value in astdb (Asterisk rewrites that value
 * only when a dynamic member is added or removed). Without cleaning it, on an
 * Asterisk restart the agent no longer in the config (removed from static)
 * would come back to the queue as a dynamic member. The value consists of
 * "|"-separated "interface;penalty;paused;..." entries (app_queue
 * dump_queue_members).
 */
function purgeStaticFromPersistentMembers($q_name, array $static_exts) {
    if (empty($static_exts)) return;
    @exec("asterisk -rx " . escapeshellarg("database get Queue/PersistentMembers $q_name"), $out);
    $value = null;
    foreach ($out ?: [] as $line) {
        if (strpos($line, 'Value: ') === 0) $value = substr($line, 7);
    }
    if ($value === null || $value === '') return;

    $static_ifaces = array_map(fn($e) => "Local/{$e}@from-internal-pbx/n", $static_exts);
    $entries = explode('|', $value);
    $kept = array_filter($entries, fn($entry) => !in_array(explode(';', $entry)[0], $static_ifaces, true));
    if (count($kept) === count($entries)) return;

    if (empty($kept)) {
        @exec("asterisk -rx " . escapeshellarg("database del Queue/PersistentMembers $q_name"));
    } else {
        @exec("asterisk -rx " . escapeshellarg("database put Queue/PersistentMembers $q_name \"" . str_replace('"', '', implode('|', $kept)) . "\""));
    }
}

