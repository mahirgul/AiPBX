<?php
/**
 * AI → External agents (/etc/asterisk/pbx/pjsip_ai_agents.conf and
 * extensions_ai_agents.conf), see src/services/ai/AiAgentService.php and
 * docs/ai-agents.md.
 *
 * Per active agent <id>:
 *  - PJSIP endpoint aiagent-<id>: outbound only. identify_by=ip without an
 *    identify section, so no request from outside ever matches it; its context
 *    is used for nothing but the agent's REFER inside a call.
 *  - [aipbx-ai-agent-<id>] (the destination): call limit (GROUP_COUNT), the
 *    caller's number, DID and call id as X-AiPBX-* headers, Dial with a ring
 *    time and a maximum call length; not reached (busy, no answer, error, limit)
 *    -> fallback destination.
 *  - [aipbx-ai-agent-xfer-<id>]: the agent's blind transfer (REFER). Whatever
 *    number it names, the call goes to the hand-over destination; without one
 *    it ends.
 */

function syncAiAgents() {
    return withSyncLock('ai_agents', '__syncAiAgentsBody');
}

function __syncAiAgentsBody() {
    require_once dirname(__DIR__) . '/services/ai/AiAgentService.php';
    $agents = [];
    try {
        $agents = getDB()->query('SELECT * FROM pbx_ai_agents WHERE is_active = 1 ORDER BY id ASC')->fetchAll(PDO::FETCH_ASSOC);
    } catch (\Throwable $e) {
        // table not migrated yet: write empty files
    }
    if (is_file(dirname(__DIR__) . '/core/PluginManager.php')) {
        require_once dirname(__DIR__) . '/core/PluginManager.php';
        $installed = PluginManager::installedMap();
        if (isset($installed['ai-agents']) && empty($installed['ai-agents']['enabled'])) {
            $agents = [];
        }
    }
    $privacyBlocked = function_exists('getSystemSetting') && getSystemSetting('privacy_block_cloud_ai', '0') === '1';
    return writeConfsWithRollback([
        'pjsip_ai_agents.conf' => buildAiAgentPjsipConf($agents),
        'extensions_ai_agents.conf' => buildAiAgentDialplan($agents, $privacyBlocked),
    ], function () {
        AsteriskHelper::assertReloadsOk([AsteriskHelper::reloadPJSIP(), AsteriskHelper::reloadDialplan()], t('sync.ctx_ai_agents'));
    }, t('sync.ctx_ai_agents'));
}

/** The URI the dialplan dials: TCP and TLS named in it, so PJSIP picks that transport. */
function aiAgentDialUri(array $agent): string {
    $p = AiAgentService::parseUri((string) $agent['sip_uri']);
    if ($p === null) {
        return '';
    }
    $uri = $p['scheme'] . ':' . ($p['user'] !== '' ? $p['user'] . '@' : '') . $p['host'] . ($p['port'] > 0 ? ':' . $p['port'] : '');
    if ($p['scheme'] === 'sip' && $agent['transport'] !== 'udp') {
        $uri .= ';transport=' . $agent['transport'];
    }
    return $uri;
}

/** @param array<int, array> $agents active agents */
function buildAiAgentPjsipConf(array $agents): string {
    // A voice agent talks: audio codecs only.
    $codecs = implode(',', array_diff(array_map('trim', explode(',', getSystemSetting('pjsip_codecs', 'opus,ulaw,alaw,g722'))), ['vp8', 'h264']));
    $conf = "; ==========================================================\n";
    $conf .= "; External AI agents (Auto-generated by AI PBX)\n";
    $conf .= "; ==========================================================\n\n";
    foreach ($agents as $a) {
        $id = (int) $a['id'];
        if (aiAgentDialUri($a) === '') {
            continue;
        }
        $transport = in_array($a['transport'], AiAgentService::TRANSPORTS, true) ? $a['transport'] : 'udp';
        $user = confValue((string) $a['auth_username']);
        $conf .= "; --- AI agent {$id}: " . dialplanText((string) $a['title']) . " ---\n";
        $conf .= "[aiagent-{$id}]\n";
        $conf .= "type=endpoint\n";
        $conf .= "transport=transport-{$transport}\n";
        $conf .= "context=aipbx-ai-agent-xfer-{$id}\n";
        $conf .= "identify_by=ip\n";
        $conf .= "disallow=all\n";
        $conf .= "allow={$codecs}\n";
        $conf .= "direct_media=no\n";
        $conf .= "rtp_symmetric=yes\n";
        $conf .= "force_rport=yes\n";
        $conf .= "rewrite_contact=yes\n";
        $conf .= "allow_transfer=yes\n";
        if ($user !== '') {
            $conf .= "outbound_auth=aiagent-{$id}-auth\n\n";
            $conf .= "[aiagent-{$id}-auth]\n";
            $conf .= "type=auth\n";
            $conf .= "auth_type=userpass\n";
            $conf .= "username={$user}\n";
            $conf .= 'password=' . confValue(AiAgentService::password($a)) . "\n";
        }
        $conf .= "\n";
    }
    if ($agents === []) {
        $conf .= "; No active AI agents\n";
    }
    return $conf;
}

/** @param array<int, array> $agents active agents */
function buildAiAgentDialplan(array $agents, ?bool $privacyBlocked = null): string {
    if ($privacyBlocked === null) {
        $privacyBlocked = function_exists('getSystemSetting') && getSystemSetting('privacy_block_cloud_ai', '0') === '1';
    }
    $conf = "; ==========================================================\n";
    $conf .= "; External AI agents (Auto-generated by AI PBX)\n";
    $conf .= "; ==========================================================\n\n";
    if ($agents === []) {
        return $conf . "; No active AI agents\n";
    }
    // Pre-dial handler on the agent's leg: who calls, on which number, which call.
    $conf .= "[aipbx-ai-agent-headers]\n";
    $conf .= "exten => s,1,Set(PJSIP_HEADER(add,X-AiPBX-Caller)=\${ARG1})\n";
    $conf .= " same => n,Set(PJSIP_HEADER(add,X-AiPBX-DID)=\${ARG2})\n";
    $conf .= " same => n,Set(PJSIP_HEADER(add,X-AiPBX-Call-ID)=\${ARG3})\n";
    $conf .= " same => n,Return()\n\n";

    foreach ($agents as $a) {
        $id = (int) $a['id'];
        $uri = aiAgentDialUri($a);
        $name = dialplanText((string) $a['title']);
        $max = max(1, (int) $a['max_concurrent']);
        $seconds = max(60, (int) $a['max_minutes'] * 60);
        $ring = max(5, (int) $a['ring_seconds']);

        $conf .= "; --- AI agent {$id}: {$name} ---\n";
        $conf .= "[aipbx-ai-agent-{$id}]\n";
        $conf .= "exten => s,1,NoOp(AI agent {$id}: {$name})\n";
        if ($privacyBlocked) {
            $conf .= " same => n,NoOp(AI agent {$id}: external data transfer blocked by privacy policy)\n";
            if ((string) $a['handover_dest_type'] !== '') {
                $conf .= buildDestinationLines((string) $a['handover_dest_type'], (string) $a['handover_dest_id']) . "\n";
                $conf .= " same => n,Hangup()\n";
            } else {
                $conf .= " same => n,Goto(fallback)\n";
            }
        } elseif ($uri === '') {
            $conf .= " same => n,Goto(fallback)\n";
        } else {
            $conf .= " same => n,Set(GROUP(aipbx_ai_agent)=a{$id})\n";
            $conf .= " same => n,GotoIf(\$[\${GROUP_COUNT(a{$id}@aipbx_ai_agent)} > {$max}]?fallback)\n";
            $conf .= " same => n,Dial(PJSIP/aiagent-{$id}/{$uri},{$ring},S({$seconds})"
                . "b(aipbx-ai-agent-headers^s^1(\${FILTER(0-9+*#,\${CALLERID(num)})},\${FILTER(0-9+*#,\${CDR(did)})},\${FILTER(0-9.,\${UNIQUEID})})))\n";
            $conf .= " same => n,GotoIf(\$[\"\${DIALSTATUS}\" = \"ANSWER\"]?done)\n";
        }
        $conf .= " same => n(fallback),NoOp(AI agent {$id}: not reached (\${DIALSTATUS}))\n";
        $conf .= buildDestinationLines((string) $a['fallback_dest_type'], (string) $a['fallback_dest_id']) . "\n";
        $conf .= " same => n(done),Hangup()\n\n";

        $conf .= "[aipbx-ai-agent-xfer-{$id}]\n";
        // h is a letter too: without its own line the pattern ran the hand-over again at hang-up.
        $conf .= "exten => h,1,NoOp(AI agent {$id}: call ended)\n";
        $conf .= "exten => _[0-9A-Za-z+*#]!,1,NoOp(AI agent {$id}: hands the call over (asked for \${FILTER(0-9A-Za-z+*#,\${EXTEN})}))\n";
        if ((string) $a['handover_dest_type'] !== '') {
            $conf .= buildDestinationLines((string) $a['handover_dest_type'], (string) $a['handover_dest_id']) . "\n";
        }
        $conf .= " same => n,Hangup()\n\n";
    }
    return $conf;
}
