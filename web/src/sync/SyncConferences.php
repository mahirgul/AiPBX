<?php
/**
 * Sync Conference Rooms Dialplan (/etc/asterisk/pbx/extensions_conferences.conf)
 */

require_once __DIR__ . '/../helpers.php';

function syncConferences() {
    return withSyncLock('conferences', '__syncConferencesBody');
}

function __syncConferencesBody() {
    $db = getDB();
    $conferences = $db->query("SELECT * FROM pbx_conferences WHERE is_active = 1 ORDER BY id ASC")->fetchAll(PDO::FETCH_ASSOC);

    $conf = "; Native Conference Rooms Dialplan Context (Auto-generated by AI PBX)\n\n";

    // 1. Dispatcher context for fast routing by room number
    $conf .= "[app-confbridge-dispatch]\n";
    $seenRooms = [];
    foreach ($conferences as $cf) {
        $id = intval($cf['id']);
        $num = preg_replace('/[^0-9]/', '', (string)$cf['room_number']);
        if ($num !== '' && !isset($seenRooms[$num])) {
            $seenRooms[$num] = true;
            $conf .= "exten => {$num},1,Goto(app-confbridge-{$id},s,1)\n";
        }
    }
    // Dynamic / Ad-hoc room fallback (e.g. mobile chat group rooms; blocked for external web-guest)
    $conf .= "exten => _.,1,NoOp(Dynamic/Ad-hoc Conference Room \${EXTEN} by \${CALLERID(num)})\n";
    $conf .= " same => n,GotoIf(\$[\"\${AIPBX_CLIENT_TYPE}\" = \"web-guest\"]?hangup_guest)\n";
    $conf .= " same => n,Set(CDR(direction)=internal)\n";
    $conf .= " same => n,Answer()\n";
    $conf .= " same => n,Set(CONFBRIDGE(bridge,video_mode)=sfu)\n";
    $conf .= " same => n,Set(CONFBRIDGE(user,announce_join_leave)=yes)\n";
    $conf .= " same => n,Set(CONFBRIDGE(user,announce_user_count)=yes)\n";
    $conf .= " same => n,Set(CONFBRIDGE(user,music_on_hold_class)=default)\n";
    $conf .= " same => n,ConfBridge(\${EXTEN})\n";
    $conf .= " same => n(hangup_guest),Hangup()\n\n";

    // Browser participants of /meet/{token}. They all share one SIP password, so each call is
    // checked here: the token from the page must belong to a meeting in this room that is open
    // for joining right now. Anything else, or a failed check, is refused.
    $conf .= "[app-meeting-guest]\n";
    $conf .= "exten => _X.,1,NoOp(Meeting guest joining room \${EXTEN})\n";
    $conf .= " same => n,Set(MEET_TOKEN=\${FILTER(a-zA-Z0-9_,\${PJSIP_HEADER(read,X-Meeting-Token)})})\n";
    $conf .= " same => n,GotoIf(\$[\"\${MEET_TOKEN}\" = \"\"]?deny)\n";
    // The prefix is required: digits in an HTTP error page must never pass for a limit.
    $conf .= " same => n,Set(MEET_CHECK=\${CURL(http://127.0.0.1/api/meeting_join_check.php?room=\${EXTEN}&token=\${MEET_TOKEN})})\n";
    $conf .= " same => n,GotoIf(\$[\"\${MEET_CHECK:0:5}\" != \"JOIN:\"]?deny)\n";
    $conf .= " same => n,Set(MEET_MAX=\${FILTER(0-9,\${MEET_CHECK:5})})\n";
    $conf .= " same => n,GotoIf(\$[\"\${MEET_MAX}\" = \"\"]?deny)\n";
    $conf .= " same => n,Set(MEET_PARTIES=\${CONFBRIDGE_INFO(parties,\${EXTEN})})\n";
    $conf .= " same => n,GotoIf(\$[0\${MEET_PARTIES} >= \${MEET_MAX}]?full)\n";
    $conf .= " same => n,Goto(app-confbridge-dispatch,\${EXTEN},1)\n";
    $conf .= " same => n(deny),Hangup(21)\n";
    $conf .= " same => n(full),Hangup(34)\n\n";

    // 2. Individual conference room contexts
    foreach ($conferences as $cf) {
        $id = intval($cf['id']);
        $num = preg_replace('/[^0-9]/', '', (string)$cf['room_number']);
        $title = dialplanText($cf['title']);
        $user_pin = preg_replace('/[^0-9]/', '', (string)($cf['user_pin'] ?? ''));
        $admin_pin = preg_replace('/[^0-9]/', '', (string)($cf['admin_pin'] ?? ''));
        $wait_marked = !empty($cf['wait_marked']) ? 'yes' : 'no';
        $end_marked = !empty($cf['end_marked']) ? 'yes' : 'no';
        $announce_join_leave = !empty($cf['announce_join_leave']) ? 'yes' : 'no';
        $announce_user_count = !empty($cf['announce_user_count']) ? 'yes' : 'no';
        $record = !empty($cf['record_conference']) ? 'yes' : 'no';
        $mute = !empty($cf['mute_on_join']) ? 'yes' : 'no';
        $moh = preg_replace('/[^a-zA-Z0-9_-]/', '', $cf['music_on_hold'] ?? 'default') ?: 'default';
        $video_mode = in_array($cf['video_mode'] ?? 'none', ['sfu', 'follow_talker', 'talker'], true) ? $cf['video_mode'] : 'none';

        $conf .= "; ---- Conference #{$id}: {$title} ({$num}) ----\n";
        $conf .= "[app-confbridge-{$id}]\n";
        $conf .= "exten => s,1,NoOp(Conference Room {$id}: {$title} - Room Number: {$num})\n";
        $conf .= " same => n,Set(CDR(direction)=internal)\n";
        $conf .= " same => n,Answer()\n";

        // ConfBridge dynamic settings
        $conf .= " same => n,Set(CONFBRIDGE(bridge,record_conference)={$record})\n";
        if ($video_mode !== 'none') {
            $conf .= " same => n,Set(CONFBRIDGE(bridge,video_mode)={$video_mode})\n";
            $conf .= " same => n,Set(CONFBRIDGE(bridge,video_update_discard)=0)\n";
            $conf .= " same => n,Set(CONFBRIDGE(bridge,remb_send_interval)=1000)\n";
            $conf .= " same => n,Set(CONFBRIDGE(bridge,remb_behavior)=average)\n";
        }
        $conf .= " same => n,Set(CONFBRIDGE(user,music_on_hold_class)={$moh})\n";
        $conf .= " same => n,Set(CONFBRIDGE(user,wait_marked)={$wait_marked})\n";
        $conf .= " same => n,Set(CONFBRIDGE(user,end_marked)={$end_marked})\n";
        $conf .= " same => n,Set(CONFBRIDGE(user,announce_join_leave)={$announce_join_leave})\n";
        $conf .= " same => n,Set(CONFBRIDGE(user,announce_user_count)={$announce_user_count})\n";
        $conf .= " same => n,Set(CONFBRIDGE(user,startmuted)={$mute})\n";

        if ($admin_pin !== '' || $user_pin !== '') {
            $conf .= " same => n,Read(CONF_PIN,conf-getpin,10,,3,10)\n";
            if ($admin_pin !== '') {
                $conf .= " same => n,GotoIf(\$[\"\${CONF_PIN}\" = \"{$admin_pin}\"]?cf_admin_{$id})\n";
            }
            if ($user_pin !== '') {
                $conf .= " same => n,GotoIf(\$[\"\${CONF_PIN}\" = \"{$user_pin}\"]?cf_user_{$id})\n";
            }
            $conf .= " same => n,Playback(conf-invalidpin)\n";
            $conf .= " same => n,Hangup()\n";

            if ($admin_pin !== '') {
                $conf .= " same => n(cf_admin_{$id}),Set(CONFBRIDGE(user,admin)=yes)\n";
                $conf .= " same => n,Set(CONFBRIDGE(user,marked)=yes)\n";
                $conf .= " same => n,Goto(cf_enter_{$id})\n";
            }
            if ($user_pin !== '') {
                $conf .= " same => n(cf_user_{$id}),Set(CONFBRIDGE(user,admin)=no)\n";
                $conf .= " same => n,Goto(cf_enter_{$id})\n";
            }
        }

        $conf .= " same => n(cf_enter_{$id}),ConfBridge({$num})\n";
        $conf .= " same => n,Hangup()\n\n";
    }

    $conf .= chatCallsDialplan();

    return writeConfWithRollback('extensions_conferences.conf', $conf, function() {
        AsteriskHelper::assertReloadsOk([AsteriskHelper::reloadDialplan()], t('sync.ctx_conferences'));
    }, t('sync.ctx_conferences'));
}

/**
 * [chat-calls-pbx]: a conference started from a group chat. The apps call
 * "cc<room>"; the room is random and every caller is checked: the endpoint
 * Asterisk authenticated must belong to a member of that chat and the call
 * must be open (api/chat_call_check.php). No reload per call: one pattern.
 */
function chatCallsDialplan(): string
{
    $check = 'http://127.0.0.1/api/chat_call_check.php';
    $c = "[chat-calls-pbx]\n";
    $c .= "exten => _ccX.,1,NoOp(Chat call room \${EXTEN:2} by \${CHANNEL(endpoint)})\n";
    $c .= " same => n,Set(CC_ROOM=\${FILTER(0-9,\${EXTEN:2})})\n";
    // "\-": a bare dash in FILTER() is a range, and the endpoint name lost its dashes.
    $c .= " same => n,Set(CC_EP=\${FILTER(a-zA-Z0-9_\\-,\${CHANNEL(endpoint)})})\n";
    $c .= " same => n,GotoIf(\$[\"\${CC_ROOM}\" = \"\" | \"\${CC_EP}\" = \"\"]?deny)\n";
    // The prefix is required: digits in an HTTP error page must never pass for a limit.
    $c .= " same => n,Set(CC_CHECK=\${CURL({$check}?event=join&room=\${CC_ROOM}&endpoint=\${CC_EP})})\n";
    $c .= " same => n,GotoIf(\$[\"\${CC_CHECK:0:5}\" != \"JOIN:\"]?deny)\n";
    $c .= " same => n,Set(CC_MAX=\${FILTER(0-9,\${CUT(CC_CHECK,:,2)})})\n";
    $c .= " same => n,Set(CC_VIDEO=\${FILTER(a-z_,\${CUT(CC_CHECK,:,3)})})\n";
    $c .= " same => n,GotoIf(\$[\"\${CC_MAX}\" = \"\"]?deny)\n";
    $c .= " same => n,GotoIf(\$[0\${CONFBRIDGE_INFO(parties,chat\${CC_ROOM})} >= \${CC_MAX}]?full)\n";
    $c .= " same => n,Set(CDR(direction)=internal)\n";
    $c .= " same => n,Answer()\n";
    $c .= " same => n,GotoIf(\$[\"\${CC_VIDEO}\" != \"follow_talker\"]?enter)\n";
    $c .= " same => n,Set(CONFBRIDGE(bridge,video_mode)=follow_talker)\n";
    $c .= " same => n,Set(CONFBRIDGE(bridge,video_update_discard)=0)\n";
    $c .= " same => n(enter),Set(CONFBRIDGE(user,music_on_hold_when_empty)=yes)\n";
    $c .= " same => n,Set(CONFBRIDGE(user,announce_join_leave)=no)\n";
    $c .= " same => n,Set(CONFBRIDGE(user,quiet)=yes)\n";
    $c .= " same => n,Set(CHANNEL(hangup_handler_push)=chat-call-left,s,1(\${CC_ROOM}))\n";
    $c .= " same => n,Set(CC_IN=\${CURL({$check}?event=parties&room=\${CC_ROOM}&parties=\$[0\${CONFBRIDGE_INFO(parties,chat\${CC_ROOM})} + 1])})\n";
    $c .= " same => n,ConfBridge(chat\${CC_ROOM})\n";
    $c .= " same => n,Hangup()\n";
    $c .= " same => n(deny),Hangup(21)\n";
    $c .= " same => n(full),Hangup(34)\n\n";
    $c .= "[chat-call-left]\n";
    $c .= "exten => s,1,Set(CC_LEFT=\${CURL({$check}?event=parties&room=\${FILTER(0-9,\${ARG1})}&parties=0\${CONFBRIDGE_INFO(parties,chat\${FILTER(0-9,\${ARG1})})})})\n";
    $c .= " same => n,Return()\n\n";
    return $c;
}
