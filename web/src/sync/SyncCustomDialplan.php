<?php
/**
 * Custom Asterisk Dialplan Contexts Sync Module (/etc/asterisk/pbx/extensions_custom.conf)
 *
 * Generates custom dialplan contexts and an internal aggregator context
 * [custom-dialplan-pbx] included in [from-internal-pbx-ortak].
 */

require_once __DIR__ . '/DialplanBuilders.php';
require_once dirname(__DIR__) . '/services/CustomDialplanService.php';

function syncCustomDialplan()
{
    return withSyncLock('custom_dialplan', '__syncCustomDialplanBody');
}

/**
 * Pure generator — builds extensions_custom.conf from an array of entries.
 *
 * @param array<int, array<string, mixed>> $entries
 */
function buildCustomDialplanConf(array $entries): string
{
    $conf = "; Custom Asterisk Dialplan Contexts (Auto-generated by AI PBX)\n";
    $conf .= "; Do not edit this file directly - manage via PBX -> Custom Dialplan in the web portal\n\n";

    $conf .= "[custom-dialplan-pbx]\n";
    $conf .= "; Includes active custom contexts flagged to be accessible from internal extensions\n";

    $internalIncludes = [];
    foreach ($entries as $e) {
        if (!empty($e['include_in_internal'])) {
            $cName = preg_replace('/[^a-zA-Z0-9_-]/', '', trim((string)($e['context_name'] ?? '')));
            if ($cName !== '') {
                $internalIncludes[] = $cName;
            }
        }
    }

    if (empty($internalIncludes)) {
        $conf .= "; (no custom contexts included in internal dialplan)\n";
    } else {
        foreach (array_unique($internalIncludes) as $cName) {
            $conf .= "include => {$cName}\n";
        }
    }

    $conf .= "\n";

    foreach ($entries as $e) {
        $title = toCleanAscii((string)($e['title'] ?? ''));
        $cName = preg_replace('/[^a-zA-Z0-9_-]/', '', trim((string)($e['context_name'] ?? '')));
        if ($cName === '') {
            continue;
        }
        // The portal refuses these when saving; a row from a restored backup or from
        // SQL never went through it, and a file directive runs as Asterisk.
        if (preg_match('/^\s*#\s*(include|tryinclude|exec|tryexec)\b/im', (string) ($e['dialplan_content'] ?? ''))
            || in_array(strtolower($cName), CustomDialplanService::RESERVED_CONTEXTS, true)) {
            error_log("Custom dialplan [{$cName}] skipped: file directive or reserved context name");
            $conf .= "; Custom Context [{$cName}] skipped: file directive or reserved context name\n\n";
            continue;
        }

        $conf .= "; =====================================================================\n";
        $conf .= "; Custom Context: {$title} [{$cName}]\n";
        if (!empty($e['description'])) {
            $conf .= "; Description: " . toCleanAscii((string)$e['description']) . "\n";
        }
        $conf .= "; =====================================================================\n";

        $rawContent = trim((string)($e['dialplan_content'] ?? ''));
        if (!preg_match('/^\s*\[' . preg_quote($cName, '/') . '\]/m', $rawContent)) {
            $conf .= "[{$cName}]\n";
        }

        $conf .= $rawContent . "\n\n";
    }

    return $conf;
}

function __syncCustomDialplanBody()
{
    require_once dirname(__DIR__) . '/repositories/CustomDialplanRepository.php';
    $entries = CustomDialplanRepository::findActive();
    $conf = buildCustomDialplanConf($entries);

    return writeConfWithRollback('extensions_custom.conf', $conf, function () {
        AsteriskHelper::assertReloadsOk(
            [AsteriskHelper::reloadDialplan()],
            t('sync.ctx_custom_dialplan')
        );
    }, t('sync.ctx_custom_dialplan'));
}
