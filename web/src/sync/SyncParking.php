<?php
/**
 * Call Parking Sync Module (/etc/asterisk/pbx/res_parking_pbx.conf + extensions_parking.conf).
 * /etc/asterisk/res_parking.conf is the repo's fixed file (the installer copies it) that pulls the
 * generated part in: the web server cannot write /etc/asterisk itself.
 */

require_once __DIR__ . '/../helpers.php';
require_once __DIR__ . '/DialplanDestinationBuilder.php';

function syncParking(): bool
{
    return withSyncLock('parking', '__syncParkingBody');
}

function getParkingConfigForSync(): array
{
    $default = [
        'is_active' => 0,
        'parkext' => '700',
        'slot_start' => 701,
        'slot_end' => 710,
        'parking_time' => 45,
        'findslot' => 'next',
        'comeback_to_origin' => 1,
        'comeback_dial_time' => 30,
        'timeout_dest_type' => null,
        'timeout_dest_id' => null,
        'moh_class' => 'default',
        'parked_play' => 'caller',
    ];
    try {
        $row = getDB()->query('SELECT * FROM pbx_parking ORDER BY id ASC LIMIT 1')->fetch(PDO::FETCH_ASSOC);
        return $row ? array_merge($default, $row) : $default;
    } catch (\Throwable $e) {
        return $default;
    }
}

function buildResParkingConf(array $cfg): string
{
    $conf = "; Call Parking Configuration (Auto-generated by AI PBX)\n";
    $conf .= "; Manual edits here will be overwritten on the next Apply.\n\n";

    if (empty($cfg['is_active'])) {
        return $conf;
    }

    $parkext = preg_replace('/[^0-9]/', '', (string) ($cfg['parkext'] ?? '700')) ?: '700';
    $start = max(1, (int) ($cfg['slot_start'] ?? 701));
    $end = max($start, (int) ($cfg['slot_end'] ?? 710));
    $time = max(10, min(600, (int) ($cfg['parking_time'] ?? 45)));
    $findslot = (($cfg['findslot'] ?? 'next') === 'first') ? 'first' : 'next';
    $comeback = !empty($cfg['comeback_to_origin']) ? 'yes' : 'no';
    $comebackDialTime = max(5, min(120, (int) ($cfg['comeback_dial_time'] ?? 30)));
    $moh = preg_replace('/[^a-zA-Z0-9_-]/', '', (string) ($cfg['moh_class'] ?? 'default')) ?: 'default';
    $playAllowed = ['caller', 'parked', 'both', 'no'];
    $parkedPlay = in_array((string) ($cfg['parked_play'] ?? 'caller'), $playAllowed, true)
        ? (string) $cfg['parked_play']
        : 'caller';

    $conf .= "[default]\n";
    $conf .= "parkext => {$parkext}\n";
    $conf .= "parkext_exclusive = yes\n";
    $conf .= "parkpos => {$start}-{$end}\n";
    $conf .= "context => parkedcalls\n";
    $conf .= "parkingtime => {$time}\n";
    $conf .= "comebacktoorigin = {$comeback}\n";
    $conf .= "comebackcontext => pbx-parking-timeout\n";
    $conf .= "comebackdialtime = {$comebackDialTime}\n";
    $conf .= "findslot => {$findslot}\n";
    $conf .= "parkedplay = {$parkedPlay}\n";
    $conf .= "parkedcalltransfers = caller\n";
    $conf .= "parkedcallreparking = caller\n";
    $conf .= "parkedcallhangup = no\n";
    $conf .= "parkedcallrecording = no\n";
    $conf .= "parkedmusicclass = {$moh}\n";
    $conf .= "\n#tryinclude \"pbx/res_parking_custom.conf\"\n";

    return $conf;
}

function buildParkingDialplanConf(array $cfg): string
{
    $conf = "; Call Parking Timeout Dialplan (Auto-generated by AI PBX)\n\n";
    $conf .= "[pbx-parking-timeout]\n";

    if (empty($cfg['is_active'])) {
        $conf .= "exten => s,1,Hangup()\n\n";
        return $conf;
    }

    $destType = trim((string) ($cfg['timeout_dest_type'] ?? ''));
    $destId = trim((string) ($cfg['timeout_dest_id'] ?? ''));

    $conf .= "exten => s,1,NoOp(Parked call timed out)\n";
    if ($destType !== '') {
        $destBlock = trim(buildDestinationLines($destType, $destId), "\r\n");
        if ($destBlock !== '') {
            $conf .= $destBlock . "\n";
        }
    }
    $conf .= " same => n,Hangup()\n";
    $conf .= "exten => _X.,1,Goto(pbx-parking-timeout,s,1)\n\n";

    return $conf;
}

function __syncParkingBody(): bool
{
    $cfg = getParkingConfigForSync();
    $label = t('pending_sync.domain_parking');
    // Lots and their timeout dialplan go back together when either reload fails.
    return writeConfsWithRollback([
        'res_parking_pbx.conf' => buildResParkingConf($cfg),
        'extensions_parking.conf' => buildParkingDialplanConf($cfg),
    ], function () use ($label) {
        AsteriskHelper::assertReloadsOk([AsteriskHelper::reloadParking(), AsteriskHelper::reloadDialplan()], $label);
    }, $label);
}
