<?php

declare(strict_types=1);

/**
 * IVR Data Steps Dialplan Sync (/etc/asterisk/pbx/extensions_ivr_data.conf)
 * Roadmap 2.3: Executes queries or HTTP requests during IVR flow and branches
 * on found / not found / timeout.
 */

function buildIvrDataStepDialplanBlock(array $step): string
{
    $id = (int)$step['id'];
    $name = toCleanAscii((string)$step['name']);
    $prompt = !empty($step['prompt_file']) ? FileHelper::sanitizeAudioPath((string)$step['prompt_file']) : '';
    $inputSource = (string)($step['input_source'] ?? 'dtmf');
    $maxDigits = max(1, min(30, (int)($step['max_digits'] ?? 10)));
    $timeout = max(1, min(30, (int)($step['input_timeout_sec'] ?? 5)));
    $channelVar = preg_replace('/[^A-Za-z0-9_]/', '', (string)($step['channel_var_name'] ?? 'IVR_DATA_VAL')) ?: 'IVR_DATA_VAL';

    $conf = "; IVR Data Step ID {$id}: {$name}\n";
    $conf .= "[aipbx-ivr-data-{$id}]\n";
    $conf .= "exten => s,1,NoOp(Executing IVR Data Step ID {$id}: {$name})\n";
    $conf .= " same => n,Answer()\n";

    if ($inputSource === 'caller_id') {
        $conf .= " same => n,Set(IVR_INPUT=\${CALLERID(num)})\n";
    } else {
        if ($prompt !== '') {
            $conf .= " same => n,Read(IVR_INPUT,{$prompt},{$maxDigits},,,{$timeout})\n";
        } else {
            $conf .= " same => n,Read(IVR_INPUT,,{$maxDigits},,,{$timeout})\n";
        }
    }

    $conf .= " same => n,Set(CURLOPT(httptimeout)=3)\n";
    $conf .= " same => n,Set(LOOKUP_RAW=\${CURL(http://127.0.0.1/api/ivr_data_lookup.php?step_id={$id}&input=\${URIENCODE(\${IVR_INPUT})}&caller_id=\${URIENCODE(\${CALLERID(num)})})})\n";
    $conf .= " same => n,Set(LOOKUP_STATUS=\${CUT(LOOKUP_RAW,|,1)})\n";
    $conf .= " same => n,Set(LOOKUP_VAL=\${CUT(LOOKUP_RAW,|,2)})\n";
    $conf .= " same => n,Set({$channelVar}=\${LOOKUP_VAL})\n";
    $conf .= " same => n,GotoIf(\$[\"\${LOOKUP_STATUS}\" = \"found\"]?found)\n";
    $conf .= " same => n,GotoIf(\$[\"\${LOOKUP_STATUS}\" = \"not_found\"]?not_found)\n";
    $conf .= " same => n,Goto(timeout)\n\n";

    // Found branch
    $conf .= " same => n(found),NoOp(IVR Data Step {$id} Found: \${LOOKUP_VAL})\n";
    $conf .= buildDestinationLines((string)($step['found_dest_type'] ?? 'hangup'), (string)($step['found_dest_id'] ?? '')) . "\n";
    $conf .= " same => n,Hangup()\n\n";

    // Not found branch
    $conf .= " same => n(not_found),NoOp(IVR Data Step {$id} Not Found)\n";
    $conf .= buildDestinationLines((string)($step['not_found_dest_type'] ?? 'hangup'), (string)($step['not_found_dest_id'] ?? '')) . "\n";
    $conf .= " same => n,Hangup()\n\n";

    // Timeout branch
    $conf .= " same => n(timeout),NoOp(IVR Data Step {$id} Timeout or Error)\n";
    $conf .= buildDestinationLines((string)($step['timeout_dest_type'] ?? 'hangup'), (string)($step['timeout_dest_id'] ?? '')) . "\n";
    $conf .= " same => n,Hangup()\n\n";

    return $conf;
}

function syncIvrDataSteps(): bool
{
    return withSyncLock('ivr_data_steps', '__syncIvrDataStepsBody');
}

function __syncIvrDataStepsBody(): bool
{
    $db = getDB();
    $steps = $db->query('SELECT * FROM pbx_ivr_data_steps WHERE is_active = 1 ORDER BY id ASC')->fetchAll(PDO::FETCH_ASSOC);

    $conf = "; ==========================================================\n";
    $conf .= "; IVR Data Steps Dialplan (Auto-generated by AI PBX)\n";
    $conf .= "; ==========================================================\n\n";

    foreach ($steps as $s) {
        $conf .= buildIvrDataStepDialplanBlock($s);
    }

    return writeConfWithRollback('extensions_ivrdata.conf', $conf, function() {
        AsteriskHelper::assertReloadsOk([AsteriskHelper::reloadDialplan()], t('sync.ctx_ivr_data'));
    }, t('sync.ctx_ivr_data'));
}
