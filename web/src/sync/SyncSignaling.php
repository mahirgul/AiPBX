<?php
/**
 * Signaling capture switch (/etc/asterisk/pbx/hep_aipbx.conf).
 *
 * hep.conf (copied from the repo on every update) keeps capture off and sends
 * to the local aipbx-signaling daemon; this file, included after it, turns it
 * on when PBX settings → Signaling says so. Only `enabled` is written: the
 * capture always goes to the local daemon, which stores the SIP ladder and
 * the RTCP quality counters (docs/signaling.md).
 *
 * Until 1.50.8 this was the signaling-capture plugin. Its file pointed res_hep
 * at 127.0.0.1:9060, where nothing listens, so with the plugin on nothing was
 * stored; the file is removed here.
 */

const SIGNALING_CONF = 'hep_aipbx.conf';
const SIGNALING_LEGACY_PLUGIN_CONF = 'hep_plugin_signaling-capture.conf';

function syncSignalingCapture()
{
    return withSyncLock('signaling', '__syncSignalingCaptureBody');
}

function signalingCaptureConf(bool $enabled): string
{
    return "; Signaling capture switch (Auto-generated by AiPBX)\n"
        . "; PBX settings -> Signaling; manual edits are LOST on the next Apply.\n"
        . "[general]\n"
        . 'enabled = ' . ($enabled ? 'yes' : 'no') . "\n";
}

function __syncSignalingCaptureBody()
{
    $enabled = getSystemSetting('signaling_capture', '0') === '1';
    writePBXConf(SIGNALING_CONF, signalingCaptureConf($enabled));
    $legacy = ASTERISK_PBX_DIR . '/' . SIGNALING_LEGACY_PLUGIN_CONF;
    if (is_file($legacy)) {
        @unlink($legacy);
    }
    // res_hep reads hep.conf and its includes again; calls are not touched.
    AsteriskHelper::execCLI('module reload res_hep.so');
    return true;
}
