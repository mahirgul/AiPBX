<?php
require_once __DIR__ . '/PhoneTemplate.php';

/**
 * Yealink T3x/T4x/T5x: <mac>.cfg (lowercase MAC) in Yealink's key = value
 * format. The shared y0000000000xx.cfg is not served: everything is in the
 * per-phone file.
 */
final class YealinkTemplate extends PhoneTemplate
{
    /** Yealink DSS key types. */
    private const KEY_TYPES = ['line' => 15, 'blf' => 16, 'speeddial' => 13, 'park' => 10, 'dnd' => 5];

    private const CODECS = ['pcmu', 'pcma', 'g722', 'g729', 'opus'];

    private const LANGUAGES = [
        'en' => 'English', 'tr' => 'Turkish', 'de' => 'German', 'fr' => 'French', 'es' => 'Spanish',
        'it' => 'Italian', 'pt' => 'Portuguese', 'ru' => 'Russian', 'pl' => 'Polish', 'nl' => 'Dutch',
        'cs' => 'Czech', 'sv' => 'Swedish', 'uk' => 'Ukrainian', 'hu' => 'Hungarian',
    ];

    public function vendor(): string
    {
        return 'yealink';
    }

    public function macFromFile(string $file): string
    {
        // y000000000028.cfg is the shared file, not a MAC.
        if (preg_match('/^y0{9}[0-9a-f]{3}\.cfg$/i', $file)) {
            return '';
        }
        return preg_match('/^([0-9a-f]{12})\.cfg$/i', $file, $m) ? PhoneModels::normalizeMac($m[1]) : '';
    }

    public function deviceFile(string $mac): string
    {
        return $mac . '.cfg';
    }

    public function contentType(): string
    {
        return 'text/plain; charset=utf-8';
    }

    public function notifyResync(): string
    {
        return 'yealink-check-cfg';
    }

    public function notifyReboot(): string
    {
        return 'yealink-reboot';
    }

    public function render(array $ctx): string
    {
        $tls = $ctx['transport'] === 'tls';
        $lines = [
            '#!version:1.0.0.1',
            '## Generated by AiPBX — changes made on the phone are overwritten at the next provisioning.',
            '',
        ];
        // Account 1 is the user's own line; the others are device-only extensions of line keys.
        $own = ['extension' => $ctx['extension'], 'display_name' => $ctx['display_name'], 'sip_password' => $ctx['sip_password']];
        foreach ([1 => $own] + ($ctx['accounts'] ?? []) as $n => $account) {
            $lines = array_merge($lines, self::accountLines((int) $n, $account, $ctx));
        }

        $lines[] = '';
        $lines[] = 'local_time.ntp_server1 = ' . self::clean($ctx['ntp'], 255);
        $lines[] = 'local_time.time_zone = ' . self::offsetHours((int) $ctx['utc_offset']);
        $lines[] = 'lang.gui = ' . (self::LANGUAGES[$ctx['language']] ?? 'English');
        $lines[] = 'lang.wui = ' . (self::LANGUAGES[$ctx['language']] ?? 'English');
        // Pressing a ringing BLF key picks the call up with *21<extension>.
        $lines[] = 'features.pickup.direct_pickup_enable = 1';
        $lines[] = 'features.pickup.direct_pickup_code = ' . self::clean($ctx['pickup_prefix']);
        $lines[] = 'static.security.user_password = admin:' . self::clean($ctx['admin_password'], 128);

        if (!empty($ctx['keys'])) {
            $lines[] = '';
            $model = PhoneModels::get($ctx['model']) ?? ['keys' => 0, 'exp_keys' => 0, 'exp_max' => 0];
            $lines = array_merge($lines, self::keyLines('linekey.%d', self::keysByPage($ctx['keys'], 0), $model['keys']));
            for ($page = 1; $page < PhoneModels::pageCount($ctx['model']); $page++) {
                $lines = array_merge($lines, self::keyLines("expansion_module.{$page}.key.%d", self::keysByPage($ctx['keys'], $page), $model['exp_keys']));
            }
        }

        // The template's own line goes, so the file holds one value for each setting.
        foreach (self::extras($ctx) as $name => $value) {
            $lines = array_values(array_filter($lines, static fn(string $line): bool => strcasecmp(trim(explode('=', $line, 2)[0]), (string) $name) !== 0));
            $lines[] = $name . ' = ' . self::clean($value, 500);
        }

        return implode("\n", $lines) . "\n";
    }

    /**
     * One SIP account of the phone.
     *
     * @param array{extension: string, display_name: string, sip_password: string} $account
     * @return list<string>
     */
    private static function accountLines(int $n, array $account, array $ctx): array
    {
        $a = "account.{$n}";
        $lines = [
            "{$a}.enable = 1",
            "{$a}.label = " . self::clean($account['extension']),
            "{$a}.display_name = " . self::clean($account['display_name']),
            "{$a}.auth_name = " . self::clean($account['extension']),
            "{$a}.user_name = " . self::clean($account['extension']),
            "{$a}.password = " . self::clean($account['sip_password'], 128),
            "{$a}.sip_server.1.address = " . self::clean($ctx['server'], 255),
            "{$a}.sip_server.1.port = " . (int) $ctx['port'],
            "{$a}.sip_server.1.transport_type = " . (['udp' => 0, 'tcp' => 1, 'tls' => 2][$ctx['transport']] ?? 0),
            "{$a}.outbound_proxy_enable = " . ($ctx['proxy'] !== '' ? 1 : 0),
            "{$a}.outbound_proxy.1.address = " . self::clean($ctx['proxy'], 255),
            "{$a}.outbound_proxy.1.port = " . ($ctx['proxy'] !== '' ? (int) $ctx['port'] : ''),
            "{$a}.srtp_encryption = " . (int) $ctx['srtp'],
            "{$a}.subscribe_mwi = 1",
            "voice_mail.number.{$n} = " . self::clean($ctx['voicemail']),
        ];
        // Codecs: the chosen ones in order, the others off.
        $priority = 1;
        foreach (self::CODECS as $codec) {
            $lines[] = "{$a}.codec.{$codec}.enable = " . (in_array($codec, $ctx['codecs'], true) ? 1 : 0);
        }
        foreach ($ctx['codecs'] as $codec) {
            if (in_array($codec, self::CODECS, true)) {
                $lines[] = "{$a}.codec.{$codec}.priority = " . $priority++;
            }
        }
        return $lines;
    }

    public function supportsExtraSettings(): bool
    {
        return true;
    }

    /**
     * Every key of a page: a defined one gets its type, an empty one is
     * cleared (type 0), so a key removed on the page disappears from the phone.
     */
    private static function keyLines(string $prefix, array $keys, int $count): array
    {
        $out = [];
        for ($pos = 1; $pos <= $count; $pos++) {
            $p = sprintf($prefix, $pos);
            $k = $keys[$pos] ?? null;
            if ($k === null || !isset(self::KEY_TYPES[$k['type']])) {
                $out[] = "{$p}.type = 0";
                continue;
            }
            $out[] = "{$p}.type = " . self::KEY_TYPES[$k['type']];
            $out[] = "{$p}.line = " . (int) ($k['account'] ?? 1);
            $out[] = "{$p}.value = " . ($k['type'] === 'line' || $k['type'] === 'dnd' ? '' : self::clean($k['target']));
            $out[] = "{$p}.label = " . self::clean($k['label']);
        }
        return $out;
    }
}
