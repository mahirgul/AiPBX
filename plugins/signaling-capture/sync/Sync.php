<?php
/**
 * Asterisk Sync Hook for `signaling-capture` plugin.
 * Safely writes `/etc/asterisk/pbx/hep_plugin_signaling-capture.conf` and reloads `res_hep.so`.
 */
return function (string $slug, array $settings): void {
    $enabled = ($settings['hep_enabled'] ?? '0') === '1';
    $addr = trim((string)($settings['capture_address'] ?? '127.0.0.1:9060'));
    if (!preg_match('/^[a-zA-Z0-9._-]+:\d{1,5}$/', $addr)) {
        $addr = '127.0.0.1:9060';
    }
    $captureId = max(1, min(999999, (int)($settings['capture_id'] ?? 2001)));
    $uuidType = in_array($settings['uuid_type'] ?? '', ['call-id', 'channel'], true) ? $settings['uuid_type'] : 'call-id';
    $pass = preg_replace('/[\r\n]+/', '', trim((string)($settings['capture_password'] ?? '')));

    $lines = [
        '; Auto-generated by AiPBX Plugin: signaling-capture',
        '[general]',
        'enabled = ' . ($enabled ? 'yes' : 'no'),
        'capture_address = ' . $addr,
        'capture_id = ' . $captureId,
        'uuid_type = ' . $uuidType,
    ];
    if ($pass !== '') {
        $lines[] = 'capture_password = ' . $pass;
    }

    $content = implode("\n", $lines) . "\n";
    if (function_exists('writePBXConf')) {
        writePBXConf('hep_plugin_signaling-capture.conf', $content);
        if (class_exists('AsteriskHelper')) {
            AsteriskHelper::execCLI('module reload res_hep.so');
        }
    }
};
